const {chromium}=require('/opt/homebrew/lib/node_modules/playwright');
const fs=require('fs');
(async()=>{
 const browser=await chromium.launch({headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(process.env.QA_URL||'http://127.0.0.1:5173/self-agent/');
 await page.getByRole('button',{name:'新的对话',exact:false}).click();
 await page.getByRole('heading',{name:'今天，想聊些什么？'}).waitFor();
 fs.mkdirSync('docs/qa',{recursive:true});
 await page.screenshot({path:'docs/qa/desktop.png',fullPage:true});
 await page.getByLabel('聊天消息').fill('我计划学习西班牙语，每周三次，请记住我的学习安排。我喜欢简洁的中文回复。请用一句话确认。');
 await page.getByRole('button',{name:'发送消息',exact:true}).click();
 await page.getByRole('button',{name:'停止生成',exact:false}).waitFor({state:'visible'});
 await page.getByRole('button',{name:'停止生成',exact:false}).waitFor({state:'hidden',timeout:180000});
 await page.locator('.message.assistant .markdown').waitFor();
 console.log('CHAT_REPLY',await page.locator('.message.assistant .markdown').innerText());
 await page.locator('.nav').getByRole('button',{name:'我的记忆',exact:false}).click();
 await page.getByRole('heading',{name:'我的记忆',exact:true}).waitFor();
 await page.waitForFunction(()=>Number(document.querySelector('.memory-summary strong')?.textContent)>=2,{},{timeout:60000});
 console.log('MEMORY_PAGE', (await page.locator('.memory-page').innerText()).slice(0,1600));
 await page.screenshot({path:'docs/qa/memory.png',fullPage:true});
 await page.getByRole('button',{name:'新的对话',exact:false}).click();
 await page.getByLabel('聊天消息').fill('你记得我计划学习哪种语言、每周几次吗？');
 await page.getByRole('button',{name:'发送消息',exact:true}).click();
 await page.getByRole('button',{name:'停止生成',exact:false}).waitFor({state:'hidden',timeout:180000});
 await page.locator('.message.assistant .markdown').waitFor();
 const recalled=await page.locator('.message.assistant .markdown').innerText();
 console.log('RECALL',recalled);
 if(!recalled.includes('西班牙')||!/[三3]/.test(recalled))throw new Error('Cross-conversation recall did not match');
 await page.screenshot({path:'docs/qa/recall.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:'docs/qa/mobile.png',fullPage:true,animations:'disabled'});
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth);
 if(overflow)throw new Error('Mobile horizontal overflow');
 if(errors.length)throw new Error('Browser errors: '+errors.join('; '));
 console.log('BROWSER_QA_OK');
 await browser.close();
})().catch(e=>{console.error(e.message);process.exit(1)});
